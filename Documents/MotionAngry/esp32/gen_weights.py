"""assets/student_<task>.txt(로지스틱 텍스트) → esp32/student_weights.h (C 배열, MA_FEAT_NAMES 순서로 재배열)."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ASSETS = HERE.parent / "android" / "app" / "src" / "main" / "assets"
NAMES = ["hp_bp0.1-1", "hp_domf", "hp_iqr", "hp_mean", "hp_p10", "hp_p90", "hp_sent", "hp_std",
         "jerk_iqr", "jerk_mean", "jerk_p10", "jerk_p90", "jerk_std", "sec_std_cv", "sec_std_mean", "still_frac"]


def load(path):
    t = Path(path).read_text().strip().split("\n")
    h = t[0].split()
    names = h[2:2 + int(h[1])]
    vec = lambda line: [float(x) for x in line.split()[1:]]
    return names, vec(t[1]), vec(t[2]), vec(t[3]), float(t[4].split()[1])


def reorder(names, v):
    out = [0.0] * 32
    for n, x in zip(names, v):
        pre, base = n[:4], n[4:]
        i = NAMES.index(base) + (0 if pre == "med_" else 16)
        out[i] = x
    return out


def main():
    lines = ["/* generated by gen_weights.py — MA_FEAT_NAMES 순서(med_ 16, iqr_ 16) */", "#ifndef MA_STUDENT_WEIGHTS_H", "#define MA_STUDENT_WEIGHTS_H"]
    for task in ("arousal", "valence"):
        names, mu, sd, w, b = load(ASSETS / f"student_{task}.txt")
        for key, v in (("mu", mu), ("sd", sd), ("w", w)):
            arr = reorder(names, v)
            lines.append(f"static const float MA_{task.upper()}_{key.upper()}[32] = {{" + ", ".join("%.9gf" % x for x in arr) + "};")
        lines.append(f"static const float MA_{task.upper()}_B = %.9gf;" % b)
    lines.append("#endif")
    (HERE / "student_weights.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", HERE / "student_weights.h")


if __name__ == "__main__":
    main()
